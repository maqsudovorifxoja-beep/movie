const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem('cineflow_lang') || 'uz';
  });

  const changeLanguage = (newLang) => {
    if (['uz', 'ru', 'en'].includes(newLang)) {
      setLang(newLang);
      localStorage.setItem('cineflow_lang', newLang);
    }
  };

  const t = translations[lang] || translations.uz;

  // Helper to extract localized movie title & description
  const getMovieTitle = (movie) => {
    if (!movie) return '';
    if (lang === 'uz' && movie.title_uz) return movie.title_uz;
    if (lang === 'ru' && movie.title_ru) return movie.title_ru;
    return movie.title || movie.title_uz || '';
  };

  const getMovieDesc = (movie) => {
    if (!movie) return '';
    if (lang === 'uz' && movie.description_uz) return movie.description_uz;
    if (lang === 'ru' && movie.description_ru) return movie.description_ru;
    return movie.description || movie.description_uz || '';
  };

  return (
    <LanguageContext.Provider value={{ lang, changeLanguage, t, getMovieTitle, getMovieDesc }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
